const nodemailer = require("nodemailer");
const path = require("path");
const fs = require("fs");
const { ZipArchive } = require("archiver");
const XLSX = require("xlsx");

function createPdfBuffer(title, dateRange) {
  const safeTitle = String(title).replace(/[()\\]/g, "\\$&");
  const safeDateRange = `Date Range: ${dateRange?.start || "-"} to ${dateRange?.end || "-"}`.replace(/[()\\]/g, "\\$&");
  const textLength = safeTitle.length + safeDateRange.length + 88;
  const objects = [
    "<< /Type /Catalog /Pages 2 0 R >>",
    "<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
    "<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Resources << /Font << /F1 4 0 R >> >> /Contents 5 0 R >>",
    "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
    `<< /Length ${textLength} >>\nstream\nBT /F1 18 Tf 72 720 Td (${safeTitle}) Tj 0 -28 Td /F1 12 Tf (${safeDateRange}) Tj ET\nendstream`,
  ];
  let pdf = "%PDF-1.4\n";
  const offsets = [0];
  objects.forEach((object, index) => {
    offsets.push(Buffer.byteLength(pdf));
    pdf += `${index + 1} 0 obj\n${object}\nendobj\n`;
  });
  const xrefOffset = Buffer.byteLength(pdf);
  pdf += `xref\n0 ${objects.length + 1}\n0000000000 65535 f \n`;
  offsets.slice(1).forEach((offset) => {
    pdf += `${String(offset).padStart(10, "0")} 00000 n \n`;
  });
  pdf += `trailer\n<< /Size ${objects.length + 1} /Root 1 0 R >>\nstartxref\n${xrefOffset}\n%%EOF`;
  return Buffer.from(pdf);
}

function createExcelBuffer(title, dateRange) {
  const workbook = XLSX.utils.book_new();
  const worksheet = XLSX.utils.aoa_to_sheet([
    [title],
    ["Generated by JSW Plant Reporting System"],
    ["Report file", title],
    ["Date Range", `${dateRange?.start || "-"} to ${dateRange?.end || "-"}`],
    ["Generated at", new Date().toISOString()],
  ]);
  XLSX.utils.book_append_sheet(workbook, worksheet, "Report");
  return XLSX.write(workbook, { bookType: "xlsx", type: "buffer" });
}

function createZipBuffer(fileList, dateRange) {
  return new Promise((resolve, reject) => {
    if (!Array.isArray(fileList) || fileList.length === 0) {
      reject(new Error("At least one report attachment is required."));
      return;
    }

    const archive = new ZipArchive({ zlib: { level: 9 } });
    const chunks = [];

    archive.on("data", (chunk) => chunks.push(chunk));
    archive.on("end", () => resolve(Buffer.concat(chunks)));
    archive.on("error", (err) => reject(err));

    for (const file of fileList) {
      if (!file || typeof file.name !== "string" || !file.name.trim()) {
        reject(new Error("Each report attachment must have a filename."));
        return;
      }

      const isXlsx = file.name.toLowerCase().endsWith(".xlsx");
      const defaultFilename = isXlsx
        ? file.name
        : (file.name.toLowerCase().endsWith(".pdf") ? file.name : `${file.name}.pdf`);

      let contentBuffer = null;
      if (file.content && Buffer.isBuffer(file.content)) {
        contentBuffer = file.content;
      } else if (file.buffer && Buffer.isBuffer(file.buffer)) {
        contentBuffer = file.buffer;
      } else if (file.contentBase64) {
        contentBuffer = Buffer.from(file.contentBase64, "base64");
      } else if (file.path && fs.existsSync(file.path)) {
        contentBuffer = fs.readFileSync(file.path);
      } else {
        throw new Error(
          `Missing generated content for ${file.name}. Download the report in the UI before sending it.`,
        );
      }

      if (!contentBuffer || contentBuffer.length < 10) {
        throw new Error(`Generated content for ${file.name} is empty or unreadable.`);
      }

      const isPdf = file.name.toLowerCase().endsWith(".pdf");
      if (isXlsx && contentBuffer.subarray(0, 2).toString() !== "PK") {
        console.warn(`[emailService] Warning: Excel content for ${file.name} lacks standard PK zip header.`);
      }

      if (isPdf && !contentBuffer.subarray(0, 10).toString().includes("%PDF-")) {
        console.warn(`[emailService] Warning: PDF content for ${file.name} lacks standard %PDF- header.`);
      }

      archive.append(contentBuffer, { name: defaultFilename });
    }

    archive.finalize();
  });
}

class EmailService {
  constructor() {
    this.transporter = null;
    this.initTransporter();
  }

  initTransporter() {
    const host = process.env.SMTP_HOST || "127.0.0.1";
    const port = parseInt(process.env.SMTP_PORT || "25", 10);
    const secure = process.env.SMTP_SECURE === "true";
    const user = process.env.SMTP_USER;
    const pass = process.env.SMTP_PASSWORD;

    const transportOptions = {
      pool: true,
      maxConnections: 5,
      maxMessages: 100,
      host,
      port,
      secure,
      tls: {
        rejectUnauthorized: process.env.SMTP_TLS_REJECT_UNAUTHORIZED !== "false",
      },
      connectionTimeout: 15000,
      greetingTimeout: 10000,
      socketTimeout: 30000,
    };

    if (user && pass) {
      transportOptions.auth = { user, pass };
    }

    this.transporter = nodemailer.createTransport(transportOptions);
  }

  async verifyConnection() {
    try {
      await this.transporter.verify();
      console.log("[SMTP] Successfully connected to local hMailServer.");
      return { success: true, message: "SMTP connection verified" };
    } catch (error) {
      console.error("[SMTP] Connection verification failed:", error.message);
      return { success: false, error: error.message };
    }
  }

  /**
   * Send Report Email
   * @param {Object} params
   * @param {string|string[]} params.to - Recipient email(s)
   * @param {string} [params.subject] - Subject line
   * @param {string[]} [params.cadence] - e.g. ['shiftwise', 'daily']
   * @param {Array<{name: string, path?: string, contentBase64?: string}>} [params.files] - List of selected report files
   * @param {string[]} [params.missingReports] - Names of reports that could not be compiled
   */
  async sendReportEmail({ to, subject, cadence = [], dateRange, files = [], missingReports = [] }) {
    if (!to) {
      throw new Error("Recipient email address is required");
    }

    let recipientList = [];
    if (Array.isArray(to)) {
      recipientList = to.map((e) => String(e).trim()).filter(Boolean);
    } else if (typeof to === "string") {
      recipientList = to.split(/[,;\s]+/).map((e) => e.trim()).filter(Boolean);
    }

    if (recipientList.length === 0) {
      throw new Error("No valid recipient email address provided");
    }
    const recipients = recipientList.join(", ");

    const formattedCadence = Array.isArray(cadence)
      ? (cadence.length > 0 ? cadence.join(", ") : "Immediate Share")
      : (typeof cadence === "string" && cadence.trim() ? cadence.trim() : "Immediate Share");

    // Resolve individual file buffers
    const resolvedFiles = [];
    let totalBytes = 0;

    for (const file of files) {
      const isXlsx = file.name.toLowerCase().endsWith(".xlsx");
      const defaultFilename = isXlsx
        ? file.name
        : (file.name.toLowerCase().endsWith(".pdf") ? file.name : `${file.name}.pdf`);

      let contentBuffer = null;
      if (file.buffer && Buffer.isBuffer(file.buffer)) {
        contentBuffer = file.buffer;
      } else if (file.contentBase64) {
        contentBuffer = Buffer.from(file.contentBase64, "base64");
      } else if (file.path && fs.existsSync(file.path)) {
        contentBuffer = fs.readFileSync(file.path);
      }

      if (contentBuffer && contentBuffer.length > 0) {
        totalBytes += contentBuffer.length;
        resolvedFiles.push({
          name: defaultFilename,
          filename: defaultFilename,
          content: contentBuffer,
          contentType: isXlsx
            ? "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet"
            : "application/pdf",
        });
      }
    }

    if (resolvedFiles.length === 0) {
      throw new Error("No readable report attachments found to dispatch.");
    }

    const now = new Date();
    const dateStamp = now.toISOString().slice(0, 10);
    const uniqueBaseNames = [...new Set(resolvedFiles.map((f) => f.name.replace(/\.(pdf|xlsx)$/i, "")))];
    const baseName = uniqueBaseNames[0] || "JSW_Plant_Reports";
    const hasDateAlready = baseName.includes(dateStamp);
    const zipFilename =
      uniqueBaseNames.length === 1
        ? (hasDateAlready ? `${baseName}.zip` : `${baseName}_${dateStamp}.zip`)
        : `JSW_Plant_Reports_${dateStamp}.zip`;

    const zipBuffer = await createZipBuffer(resolvedFiles, dateRange);
    const attachments = [
      {
        filename: zipFilename,
        content: zipBuffer,
        contentType: "application/zip",
      },
    ];
    const attachmentLabel = `&#128230; ${zipFilename} <span style="font-size: 11px; color: #64748b; font-weight: normal;">(ZIP containing ${resolvedFiles.length} reports)</span>`;

    const missingNotice =
      missingReports && missingReports.length > 0
        ? `
        <div style="background-color: #fffbeb; border: 1px solid #fde68a; border-left: 4px solid #f59e0b; padding: 12px 16px; margin: 16px 0; border-radius: 4px; font-size: 13px; color: #92400e;">
          <strong>&#9888; Warning - Incomplete Bundle:</strong>
          <p style="margin: 4px 0 0 0;">The following report(s) could not be compiled at dispatch time and were excluded from this attachment:</p>
          <ul style="margin: 4px 0 0 0; padding-left: 20px;">
            ${missingReports.map((r) => `<li><strong>${r}</strong></li>`).join("")}
          </ul>
        </div>
        `
        : "";

    const htmlBody = `
      <div style="font-family: Arial, sans-serif; color: #152552; max-width: 650px; margin: 0 auto; border: 1px solid #e2e8f0; border-radius: 8px; overflow: hidden;">
        <div style="background-color: #2744A0; padding: 18px 24px; color: white;">
          <h2 style="margin: 0; font-size: 20px;">JSW Plant Reporting System</h2>
          <p style="margin: 4px 0 0 0; font-size: 13px; opacity: 0.9;">Automated Report Distribution</p>
        </div>
        <div style="padding: 24px; background-color: #ffffff;">
          <p style="font-size: 14px; margin-top: 0;">Hello,</p>
          <p style="font-size: 14px;">Please find attached the requested report documents bundled together in a ZIP file.</p>
          
          ${missingNotice}

          <table style="width: 100%; border-collapse: collapse; margin: 18px 0; font-size: 13px;">
            <tr style="border-bottom: 1px solid #e2e8f0;">
              <td style="padding: 8px 0; font-weight: bold; width: 140px; color: #4a5568;">Cadence:</td>
              <td style="padding: 8px 0; color: #2744A0; font-weight: 600;">${formattedCadence}</td>
            </tr>
            <tr style="border-bottom: 1px solid #e2e8f0;">
              <td style="padding: 8px 0; font-weight: bold; color: #4a5568;">Date Range:</td>
              <td style="padding: 8px 0; color: #2744A0; font-weight: 600;">${dateRange?.startDate || dateRange?.start || "-"} to ${dateRange?.endDate || dateRange?.end || "-"}</td>
            </tr>
            <tr style="border-bottom: 1px solid #e2e8f0;">
              <td style="padding: 8px 0; font-weight: bold; color: #4a5568;">Attachment:</td>
              <td style="padding: 8px 0; color: #0284c7; font-weight: bold;">
                ${attachmentLabel}
              </td>
            </tr>
            <tr style="border-bottom: 1px solid #e2e8f0;">
              <td style="padding: 8px 0; font-weight: bold; color: #4a5568; vertical-align: top;">Reports Included:</td>
              <td style="padding: 8px 0;">
                <ul style="margin: 0; padding-left: 20px;">
                  ${resolvedFiles.map((f) => `<li><strong>${f.name}</strong></li>`).join("")}
                </ul>
              </td>
            </tr>
            <tr style="border-bottom: 1px solid #e2e8f0;">
              <td style="padding: 8px 0; font-weight: bold; color: #4a5568;">Timestamp:</td>
              <td style="padding: 8px 0;">${now.toLocaleString()}</td>
            </tr>
          </table>
          </table>

          <p style="font-size: 12px; color: #718096; margin-bottom: 0;">
            This transmission was generated inside the plant network via local hMailServer.
          </p>
        </div>
        <div style="background-color: #f7fafc; padding: 12px 24px; text-align: center; font-size: 11px; color: #a0aec0; border-top: 1px solid #edf2f7;">
          SCHAEFFLER / JSW &copy; ${now.getFullYear()} All rights reserved.
        </div>
      </div>
    `;

    const mailOptions = {
      from: process.env.SMTP_FROM || "JSW Reports <juned.khan@dacpl.in>",
      to: recipients,
      subject:
        subject ||
        `[JSW Report] ${uniqueBaseNames.join(", ")} (${formattedCadence})`,
      html: htmlBody,
      attachments,
    };

    try {
      const info = await this.transporter.sendMail(mailOptions);
      return {
        success: true,
        messageId: info.messageId,
        accepted: info.accepted,
        rejected: info.rejected,
      };
    } catch (sendErr) {
      const isConnErr =
        sendErr.code === "ECONNRESET" ||
        sendErr.code === "ESOCKET" ||
        sendErr.code === "ETIMEDOUT" ||
        sendErr.code === "ECONNREFUSED" ||
        String(sendErr.message || "").toLowerCase().includes("closed");

      if (isConnErr) {
        console.warn(`[SMTP] Connection reset/dropped (${sendErr.code || sendErr.message}). Re-initializing transport and retrying once...`);
        this.initTransporter();
        const retryInfo = await this.transporter.sendMail(mailOptions);
        return {
          success: true,
          messageId: retryInfo.messageId,
          accepted: retryInfo.accepted,
          rejected: retryInfo.rejected,
          retried: true,
        };
      }
      throw sendErr;
    }
  }
}

module.exports = new EmailService();
